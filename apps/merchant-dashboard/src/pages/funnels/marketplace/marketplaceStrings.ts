export type MarketStrings = (typeof MARKET_STRINGS)["en"];

export const LANGUAGES: MarketplaceLanguage[] = ["ar", "en", "fr"];

export const categoryLabel = (t: MarketStrings, c: MarketplaceCategory): string => t[`cat_${c}`];
export const languageLabel = (t: MarketStrings, l: MarketplaceLanguage): string => t[`lang_${l}`];
export const statusLabel = (t: MarketStrings, s: MarketplaceSubmissionStatus): string => t[`status_${s}`];

export const STATUS_TONE: Record<MarketplaceSubmissionStatus, "warning" | "success" | "danger" | "neutral"> = {
  pending: "warning",
  approved: "success",
  rejected: "danger",
  withdrawn: "neutral",
};

/** «٣ صفحات · اتستخدم مرتين» — the counts on a card, in the viewer's digits. */
export function countsLine(t: MarketStrings, stepCount: number, usesCount: number): string {
  const used = usesCount === 0 ? t.usedNone : pluralOf(t, "used", usesCount);
  return `${pluralOf(t, "pages", stepCount)} · ${used}`;
}
